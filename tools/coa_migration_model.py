STOP = {"ON", "OF", "THE", "AND", "FOR", "A", "TO", "FROM", "INT", "COMMISSION", "TOTAL", "IN"}


def _tok(s):
    return {t for t in re.split(r"[^A-Z0-9]+", s.upper()) if t and t not in STOP}


def sim(a, b):
    x, y = _tok(a), _tok(b)
    return len(x & y) / max(1, len(x | y))


def migrate():
    """leaf 계정별 이행 결과 목록."""
    out = []
    for a in LIVE:
        if not a["leaf"]:
            continue
        c = a["code"]
        auto = GBS.get(c, [])
        auto_s = " / ".join(f'{h["code"]} {h["name"].strip()}' for h in auto)
        if c in OVR:
            tgt, kind, note = OVR[c]
            if kind == "AUTO" and auto:
                kind = "AUTO 일치"
        else:
            r = rule(c)
            if r:
                tgt, kind, note = r
            elif auto:
                best = max(sim(a["name"], h["name"]) for h in auto)
                tgt = auto[0]["code"] if len(auto) == 1 else " / ".join(h["code"] for h in auto)
                kind, note = ("AUTO 일치", "") if best >= 0.34 else ("AUTO 확인", "이름 유사도 낮음")
            else:
                tgt, kind, note = "", "미매핑", "0930 GBS열에 대응 없음"
        if tgt.startswith("→"):
            twin = tgt[1:]
            base = OVR.get(twin, (None,))[0] or (GBS.get(twin, [{}])[0].get("code") if GBS.get(twin) else "")
            tgt = f"{base} (대응)" if base else f"{twin} 대응"
        out.append(dict(stmt=a["stmt"], side=a["side"], code=c, name=a["name"], amt=a["amt"], auto=auto_s, tgt=tgt, kind=kind, note=note))
    return out


def targets_of(t):
    return [x.strip() for x in t.replace("(대응)", "").split("/") if x.strip() and x.strip()[0].isdigit()]


def validate():
    known = set(CM.ALL) | {n[0] for n in NEW2}
    import coa_review_model as RM
    known |= {r["code"] for r in RM.R if r["kind"] == "신규"}
    errs = []
    for n in NEW2:
        if n[0] in CM.ALL:
            errs.append(f"신규 중복 {n[0]}")
    res = migrate()
    for m in res:
        for t in targets_of(m["tgt"]):
            if t not in known:
                errs.append(f"대상 없음 {m['code']} → {t}")
        if m["amt"] and m["kind"] in ("미매핑", "비활성", "대응계정") and m["code"][0] not in "67":
            errs.append(f"잔액 있는데 대상 없음 {m['code']} {m['amt']}")
    return errs, res


